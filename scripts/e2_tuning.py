"""E2 tuning (Task 15): generate the one-seed grid configs, then pick the best per variant.

    python scripts/e2_tuning.py make     # writes configs/tuning_runs/E2/*.yaml from configs/tuning.yaml
    python scripts/e2_tuning.py select   # reads results/runs/*/{resolved.yaml,metrics.csv}

`make` refuses to run while `equal_budget_policy` in configs/tuning.yaml is null:
the group must first decide how standard KD gets a budget equal to DFD's.
`select` ranks by validation word accuracy on subset "all", breaking ties by
higher 1-NED, then by the grid order in configs/tuning.yaml (smaller values first).
"""

import argparse
import copy
import csv
import itertools
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dfd.config import load_config, validate_config  # noqa: E402


GRIDS = {"ti_dfd": "dfd_grid", "ti_kd": "standard_kd_grid"}
BASES = {"ti_dfd": "configs/runs/E2/ti_dfd_s42.yaml", "ti_kd": "configs/runs/E2/ti_kd_s42.yaml"}
KEYS = {"temperature": ("temperature",), "lambda": ("lambda",), "tone_weight": ("component_weights", "tone")}


def trial_name(variant: str, values: dict) -> str:
    short = {"temperature": "tau", "lambda": "lam", "tone_weight": "wt"}
    return variant + "".join(f"_{short[key]}{values[key]:g}" for key in KEYS if key in values)


def grid_trials(policy: dict, variant: str) -> list[dict]:
    grid = policy[GRIDS[variant]]
    unknown = set(grid) - set(KEYS)
    if unknown:
        raise ValueError(f"Unknown grid keys for {variant}: {sorted(unknown)}")
    names = list(grid)
    return [dict(zip(names, values)) for values in itertools.product(*(grid[name] for name in names))]


def apply_trial(base: dict, values: dict, seed: int) -> dict:
    config = copy.deepcopy(base)
    config["seed"] = seed
    config["stage"] = "tune"
    for key, value in values.items():
        target = config["distillation"]
        *parents, leaf = KEYS[key]
        for parent in parents:
            target = target[parent]
        target[leaf] = float(value)
    config["evaluation"]["splits"] = ["validation"]
    config["evaluation"]["subsets"] = ["all"]
    validate_config(config)
    return config


def make(policy_path: Path, out_dir: Path) -> list[Path]:
    policy = yaml.safe_load(policy_path.read_text(encoding="utf-8"))
    if not policy.get("equal_budget_policy"):
        raise SystemExit(
            "configs/tuning.yaml: equal_budget_policy is null. Decide how standard KD gets the same trial budget "
            "as DFD (12 trials vs 6 listed), edit standard_kd_grid accordingly and record the policy, then rerun."
        )
    written = []
    out_dir.mkdir(parents=True, exist_ok=True)
    for variant, base_path in BASES.items():
        base = load_config(ROOT / base_path)
        for values in grid_trials(policy, variant):
            config = apply_trial(base, values, policy["tuning_seed"])
            path = out_dir / f"{trial_name(variant, values)}.yaml"
            header = f"# Generated by scripts/e2_tuning.py from {base_path}; policy: {policy['equal_budget_policy']}\n"
            path.write_text(header + yaml.safe_dump(config, sort_keys=False, allow_unicode=True), encoding="utf-8")
            written.append(path)
    counts = {variant: len(grid_trials(policy, variant)) for variant in BASES}
    print(f"Wrote {len(written)} configs to {out_dir}: {counts}")
    if len(set(counts.values())) != 1:
        print("WARNING: trial counts differ between DFD and standard KD; report this in the paper.")
    return written


def read_runs(runs_dir: Path, split: str) -> list[dict]:
    rows = []
    for folder in sorted(path for path in runs_dir.iterdir() if path.is_dir()):
        resolved, metrics = folder / "resolved.yaml", folder / "metrics.csv"
        if not resolved.exists() or not metrics.exists():
            continue
        config = yaml.safe_load(resolved.read_text(encoding="utf-8"))
        if config.get("experiment") != "E2" or config.get("stage") != "tune":
            continue
        with metrics.open(encoding="utf-8", newline="") as handle:
            matches = [row for row in csv.DictReader(handle) if row["split"] == split and row["subset"] == "all"]
        if len(matches) != 1:
            print(f"Skipping {folder.name}: expected one {split}/all metrics row, found {len(matches)}")
            continue
        kd = config["distillation"]
        values = {"temperature": kd["temperature"], "lambda": kd["lambda"]}
        if config["variant"] == "ti_dfd":
            values["tone_weight"] = kd["component_weights"]["tone"]
        rows.append({
            "variant": config["variant"], "values": values, "run_id": folder.name,
            "commit_hash": matches[0]["commit_hash"],
            "word_acc": float(matches[0]["word_acc"]), "ned_score": float(matches[0]["ned_score"]),
        })
    return rows


def select(policy_path: Path, runs_dir: Path) -> dict[str, dict]:
    policy = yaml.safe_load(policy_path.read_text(encoding="utf-8"))
    split = policy["selection_split"]
    rows = read_runs(runs_dir, split)
    best = {}
    for variant in BASES:
        order = {trial_name(variant, values): index for index, values in enumerate(grid_trials(policy, variant))}
        candidates = [row for row in rows if row["variant"] == variant]
        missing = set(order) - {trial_name(variant, row["values"]) for row in candidates}
        if missing:
            print(f"{variant}: {len(missing)} grid trials have no results yet: {sorted(missing)}")
        if not candidates:
            continue
        candidates.sort(key=lambda row: (-row["word_acc"], -row["ned_score"], order.get(trial_name(variant, row["values"]), len(order))))
        best[variant] = candidates[0]
        print(f"\n{variant} on {split} (best first):")
        print("trial,word_acc,ned_score,run_id")
        for row in candidates:
            print(f"{trial_name(variant, row['values'])},{row['word_acc']:.4f},{row['ned_score']:.4f},{row['run_id']}")
    return best


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["make", "select"])
    parser.add_argument("--policy", type=Path, default=ROOT / "configs/tuning.yaml")
    parser.add_argument("--out", type=Path, default=ROOT / "configs/tuning_runs/E2")
    parser.add_argument("--runs", type=Path, default=ROOT / "results/runs")
    args = parser.parse_args()
    if args.command == "make":
        make(args.policy, args.out)
    else:
        best = select(args.policy, args.runs)
        for variant, row in best.items():
            print(f"\nSelected {variant}: {row['values']} (run {row['run_id']}, commit {row['commit_hash'][:12]})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
